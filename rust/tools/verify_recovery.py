"""Verify native GUI crash/reopen recovery and seven report/recovery captures.

Windows: python tools/verify_recovery.py --gui PATH --out NEW_DIRECTORY
Linux: xvfb-run -a -s '-screen 0 1920x1080x24' python3 tools/verify_recovery.py ...

Uses private child-process roots and generated CC0 synthetic audio. No installer,
clipboard, model download, report submission, or physical listening is exercised.
"""
import argparse
from contextlib import contextmanager
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import math
import os
from pathlib import Path
import re
import shutil
import struct
import subprocess
import sys
from threading import Event
import time
import traceback
import wave


def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def digest(path):
    result = hashlib.sha256()
    with path.open('rb') as file:
        for block in iter(lambda: file.read(1024 * 1024), b''):
            result.update(block)
    return result.hexdigest()


def write_json(path, value):
    with path.open('x', encoding='utf-8') as file:
        json.dump(value, file, indent=2, ensure_ascii=False)
        file.write('\n')


def synthetic_copy(out, runtime):
    """Create a deterministic stereo fixture; only its private copy is renamed."""
    original = out / 'synthetic-cc0.wav'
    rate = 48000
    with wave.open(str(original), 'wb') as audio:
        audio.setparams((2, 2, rate, 0, 'NONE', 'not compressed'))
        for second in range(12):
            frames = bytearray()
            for frame in range(rate):
                t = second + frame / rate
                envelope = min(t * 10, 1, (12 - t) * 10)
                pulse = 0.7 + 0.3 * math.sin(2 * math.pi * 2 * t) ** 2
                left = 0.18 * math.sin(2 * math.pi * 81 * t) + 0.08 * math.sin(2 * math.pi * 997 * t)
                right = 0.16 * math.sin(2 * math.pi * 83 * t) + 0.09 * math.sin(2 * math.pi * 660 * t)
                frames.extend(struct.pack('<hh', int(32767 * left * envelope * pulse),
                                          int(32767 * right * envelope * pulse)))
            audio.writeframes(frames)
    source = runtime / 'Example source.wav'
    shutil.copy2(original, source)
    (out / 'FIXTURE-CREDITS.txt').write_text(
        'Deterministic synthetic stereo verification signal generated by verify_recovery.py.\n'
        'CC0-1.0: freely usable verification audio; no third-party recording or real song.\n', encoding='utf-8')
    return original, source


@contextmanager
def private_pointer():
    if not sys.platform.startswith('linux'):
        yield
        return
    display = os.environ.get('DISPLAY', '')
    require(re.fullmatch(r':[1-9][0-9]*(?:\.[0-9]+)?', display),
            'Run this Linux verifier under a private xvfb-run display, not a desktop session')
    from linux_test_display import park_pointer_until
    stop = Event()
    with ThreadPoolExecutor(max_workers=1) as executor:
        future = executor.submit(park_pointer_until, stop)
        try:
            time.sleep(0.1)
            if future.done():
                future.result()
            yield
        finally:
            stop.set()
            future.result(timeout=10)


def private_environment(out, app):
    private = out / 'private'
    paths = {name: private / name for name in ('home', 'config', 'data', 'cache', 'runtime', 'temp', 'local', 'roaming')}
    for path in paths.values():
        path.mkdir(parents=True)
        if os.name != 'nt':
            path.chmod(0o700)
    environment = dict(os.environ, HOME=str(paths['home']), USERPROFILE=str(paths['home']),
                       LOCALAPPDATA=str(paths['local']), APPDATA=str(paths['roaming']),
                       XDG_CONFIG_HOME=str(paths['config']), XDG_DATA_HOME=str(paths['data']),
                       XDG_CACHE_HOME=str(paths['cache']), XDG_STATE_HOME=str(paths['data'] / 'state'),
                       XDG_RUNTIME_DIR=str(paths['runtime']), TEMP=str(paths['temp']),
                       TMP=str(paths['temp']), TMPDIR=str(paths['temp']), RAYON_NUM_THREADS='2')
    if sys.platform.startswith('linux'):
        alsa = private / 'alsa-null.conf'
        alsa.write_text('pcm.!default { type null }\n', encoding='utf-8')
        environment.update(ALSA_CONFIG_PATH=str(alsa), LIBGL_ALWAYS_SOFTWARE='1',
                           WINIT_X11_SCALE_FACTOR='1', XDG_SESSION_TYPE='x11')
        environment.pop('WAYLAND_DISPLAY', None)
        environment.pop('WAYLAND_SOCKET', None)
    preferences = (paths['config'] / 'slimeybeats-ez-master' if sys.platform.startswith('linux') else app / 'user_data')
    preferences.mkdir(parents=True)
    write_json(preferences / 'update-preferences.json', {'automatic': False, 'last_check': 0})
    return environment, paths, preferences


def state_for(capture, size, name):
    data = capture.read_bytes()
    require(data[:8] == b'\x89PNG\r\n\x1a\n' and len(data) >= 24, f'{name}: missing/invalid PNG')
    width, height = struct.unpack('>II', data[16:24])
    scale = width / size[0]
    require(0.5 <= scale <= 4 and abs(height - size[1] * scale) <= 1,
            f'{name}: capture does not match the requested logical size at a uniform DPI scale')
    if sys.platform.startswith('linux'):
        require((width, height) == size, f'{name}: isolated X11 scale was not 1')
    state = json.loads(capture.with_suffix('.state.json').read_text(encoding='utf-8'))
    for field in ('error', 'recovery_error', 'update_error'):
        require(field in state and state[field] is None, f'{name}: {field}: {state.get(field)}')
    require(state.get('update_check_enabled') is False, f'{name}: automatic update checks were not disabled')
    return {'name': name, 'capture': capture.name, 'png_sha256': digest(capture),
            'width': width, 'height': height, 'logical_size': list(size), 'pixels_per_point': scale, 'state': state}


def checkpoints(root):
    points = []
    verified = {}
    for file in sorted((root / 'runs').glob('*/checkpoints/*.json')):
        require(file.stat().st_size <= 8 * 1024 * 1024, 'Oversized checkpoint metadata')
        envelope = json.loads(file.read_text(encoding='utf-8'))
        require(envelope['owner'] == {'kind': 'slimeybeats-private-recovery', 'version': 1}, 'Unexpected checkpoint owner')
        wire = envelope['data_json']
        require(hashlib.sha256(wire.encode('utf-8')).hexdigest() == envelope['sha256'], 'Checkpoint wire checksum mismatch')
        data = json.loads(wire)
        require(data['run_id'] == file.parent.parent.name and file.name == f'{data["generation"]:020}.json', 'Checkpoint identity mismatch')
        for attachment in data['audio']:
            sha = attachment['sha256']
            require(re.fullmatch('[0-9a-f]{64}', sha), 'Invalid attachment digest')
            blob = root / 'blobs' / sha
            require(not blob.is_symlink() and not (blob / 'audio.wav').is_symlink(), 'Unexpected linked attachment')
            require(json.loads((blob / 'blob.json').read_text()) == attachment, 'Blob/reference metadata mismatch')
            if sha not in verified:
                audio = blob / 'audio.wav'
                require(audio.stat().st_size == attachment['bytes'] and digest(audio) == sha, 'Saved audio digest/length mismatch')
                verified[sha] = attachment['bytes']
        points.append({'run': data['run_id'], 'generation': data['generation'],
                       'audio': data['audio'], 'payload': data['payload'], 'wire_sha256': envelope['sha256']})
    require(points, 'No committed recovery checkpoints')
    return points


class Verifier:
    def __init__(self, gui, out):
        self.out = out
        # Four private directory levels prevent development-root ancestor discovery
        # even when --out is a fresh directory immediately beneath a checkout.
        self.app = out / 'runtime' / 'isolated' / 'application' / 'bin'
        self.app.mkdir(parents=True)
        self.gui = self.app / ('SlimeyBeats-EZ-Master.exe' if os.name == 'nt' else 'slimeybeats-ez-master-live')
        shutil.copy2(gui, self.gui)
        self.environment, self.paths, self.preferences = private_environment(out, self.app)
        self.studio = out / 'Private studio'
        self.recovery = out / 'Recovery data'
        self.records = []
        self.creationflags = subprocess.CREATE_NO_WINDOW if os.name == 'nt' else 0

    def command(self, capture, extra, size):
        return [str(self.gui), '--studio-data', str(self.studio), '--recovery-data', str(self.recovery),
                *map(str, extra), '--capture-ui', str(capture), '--capture-size', *map(str, size)]

    def run(self, name, extra=(), size=(1480, 940), crash=False):
        capture = self.out / (name + '.png')
        with (self.out / (name + '.stdout.log')).open('x', encoding='utf-8') as stdout, \
             (self.out / (name + '.stderr.log')).open('x', encoding='utf-8') as stderr:
            child = subprocess.Popen(self.command(capture, extra, size), cwd=self.app, env=self.environment,
                                     stdout=stdout, stderr=stderr, creationflags=self.creationflags)
            try:
                deadline = time.monotonic() + 180
                record = None
                while time.monotonic() < deadline:
                    if capture.exists() and capture.with_suffix('.state.json').exists():
                        try:
                            record = state_for(capture, size, name)
                            break
                        except (json.JSONDecodeError, OSError):
                            pass  # The renderer's sidecar may still be completing.
                    require(child.poll() is None, f'{name}: owned GUI exited before a valid capture; see its logs')
                    time.sleep(0.1)
                require(record is not None, f'{name}: capture timed out; see its logs')
                if crash:
                    state = record['state']
                    require(state['recovery_saved'] and state['preview_ready'] and state['playback_ready'], 'Crash must follow a completed playable recovery point')
                    require(child.poll() is None, 'The GUI did not remain open for abrupt termination')
                    points = checkpoints(self.recovery)
                    require(all(not (self.recovery / 'runs' / p['run'] / 'clean.json').exists() for p in points), 'Crash run was already marked clean')
                    child.kill()  # SIGKILL / TerminateProcess, only this owned Popen.
                status = child.wait(timeout=30)
                require((status != 0) if crash else (status == 0), f'{name}: unexpected owned-process exit {status}')
                record.update(exit_code=status, owned_pid=child.pid, abrupt_termination=crash)
                self.records.append(record)
                return record
            finally:
                if child.poll() is None:
                    child.kill()
                    child.wait(timeout=15)

    def verify(self):
        for label, size in (('wide', (1480, 940)), ('compact', (1100, 720))):
            self.run('report-' + label, ['--capture-learning', 'report'], size)
            preview = self.run('report-preview-' + label, ['--capture-learning', 'report-preview'], size)
            require(preview['state']['support_preview_ready'], 'Report preview was not prepared')
        original, source = synthetic_copy(self.out, self.app)
        source_sha = digest(source)
        before = self.run('before-crash', [source, '--auto-master', '--view', 'eq', '--capture-wait-recovery', '--capture-stay-open'], crash=True)
        before_points = checkpoints(self.recovery)
        before_latest = max(before_points, key=lambda p: p['generation'])
        require(before_latest['payload']['tracks'] and before_latest['audio'], 'Saved point has no loaded track/audio')
        require(digest(source) == source_sha, 'Mastering changed the synthetic input')
        moved = source.with_name('Example source moved.wav')
        source.rename(moved)
        restored = self.run('restored-after-crash', ['--capture-restore-recovery', '--capture-wait-recovery'])
        require(restored['state']['recovery_restored'] and restored['state']['recovery_saved'], 'Restoration did not resave the recovered draft')
        require(restored['state']['preview_ready'] and restored['state']['playback_ready'], 'Restored master/playback was not prepared')
        points = checkpoints(self.recovery)
        restored_points = [p for p in points if p['run'] != before_latest['run']]
        require(restored_points, 'Restore did not commit a separate recovery run')
        after_latest = max(restored_points, key=lambda p: p['generation'])
        require(before_latest['audio'] == after_latest['audio'], 'Recovered attachment indices/digests/layout changed')
        require(before_latest['payload']['tracks'] == after_latest['payload']['tracks'], 'Recovered tracks/analysis/settings references changed')
        require((self.recovery / 'runs' / after_latest['run'] / 'clean.json').is_file(), 'Normal restored GUI exit did not mark its saved run clean')
        history = self.run('recovery-history', ['--capture-learning', 'recovery'], (1100, 720))
        require(history['state']['recovery_points'] >= 2, 'History did not show both prior runs')
        require(not source.exists() and digest(moved) == source_sha == digest(original), 'Moving/restoring changed original input bytes')
        require(len(self.records) == 7, 'Expected seven renderer captures')
        require(not any((self.studio).rglob('*.wav')), 'Unexpected Studio output')
        require(not any((self.paths['data']).rglob('*.wav')), 'Master preview unexpectedly exported audio')
        preferences = json.loads((self.preferences / 'update-preferences.json').read_text())
        require(preferences['automatic'] is False, 'Automatic update preference changed')
        return {'status': 'passed', 'gui_source_sha256': digest(self.gui), 'fixture': 'generated synthetic stereo / CC0-1.0',
                'owned_process_abrupt_termination': True, 'original_input_moved_before_restore': True,
                'original_input_bytes_preserved': True, 'recovered_attachment_manifests_identical': True,
                'recovered_track_metadata_identical': True, 'restored_copy_resaved_and_normal_exit_clean': True,
                'private_roots': {'app': str(self.app), 'studio': str(self.studio), 'recovery': str(self.recovery)},
                'automatic_update_checks_disabled': True, 'captures': self.records,
                'audio_backend': 'ALSA null (synthetic)' if sys.platform.startswith('linux') else 'native default output; physical listening not tested',
                'limits': ['Renderer/diagnostic-flow checks, not pointer interaction or screen-reader acceptance.',
                           'No physical-device audibility, file-picker portal, clipboard, report submission or installer check.']}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--gui', type=Path, required=True, help='Built native GUI executable, copied before use')
    parser.add_argument('--out', type=Path, required=True, help='Fresh private evidence directory; must not exist')
    args = parser.parse_args()
    gui = args.gui.resolve(strict=True)
    require(gui.is_file(), '--gui must be a built executable')
    out = args.out.absolute()
    require(not out.is_symlink() and not out.exists(), '--out must be a fresh directory')
    out.mkdir(parents=True, exist_ok=False)
    if os.name != 'nt':
        out.chmod(0o700)
    try:
        verifier = Verifier(gui, out)
        with private_pointer():
            result = verifier.verify()
        result['gui_original_sha256'] = digest(gui)
        require(result['gui_original_sha256'] == result['gui_source_sha256'], 'Source/copied GUI hashes differ')
    except Exception as error:
        write_json(out / 'verification.json', {'status': 'failed', 'error': str(error), 'traceback': traceback.format_exc()})
        raise
    write_json(out / 'verification.json', result)
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
